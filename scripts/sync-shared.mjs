#!/usr/bin/env node
// Copies the shared rules engine into the Edge Functions tree.
//
// Supabase bundles each function from `supabase/functions`, so code shared
// with the mobile app (packages/rules-engine) is vendored into
// `supabase/functions/_shared/rules-engine` before serve/deploy/check.
// The copy is git-ignored: packages/rules-engine is the single source of truth.
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'packages/rules-engine/src');
const target = join(root, 'supabase/functions/_shared/rules-engine');

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
cpSync(source, target, { recursive: true });

const banner = '// GENERATED by scripts/sync-shared.mjs from packages/rules-engine/src. Do not edit.\n';
let files = 0;
const stamp = (dir) => {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) stamp(path);
    else if (path.endsWith('.ts')) {
      writeFileSync(path, banner + readFileSync(path, 'utf8'));
      files++;
    }
  }
};
stamp(target);
console.log(`synced ${files} files -> ${relative(root, target)}`);
